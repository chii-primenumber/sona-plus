import assert from 'node:assert/strict'
import path from 'node:path'

export async function verifyRichTooltips(page,out) {
  const run=(method)=>page.evaluate(async(method)=>(await import('/qa-local/rich-tooltip-fixture.tsx'))[method](),method)
  const rich=page.locator('#qa-rich-tooltip')
  const tooltip=page.locator('.rh-asset-tooltip')
  const color=(scope,semantic)=>scope.locator(`[data-game-semantic="${semantic}"]`).first().evaluate((node)=>getComputedStyle(node).color)
  const assetRoute=async(route)=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48"><rect width="48" height="48" fill="#203044"/></svg>'})
  await page.route('https://data.aramkit.cn/assets/**',assetRoute)
  let skinRequests=0
  const skinRoute=async(route)=>{skinRequests++;return route.fulfill({json:{skins:[{id:86003,name:'模拟皮肤名称'}]}})}
  await page.route('**/lol-game-data/assets/v1/champions/86.json',skinRoute)
  try {
    await run('native')
    for(const row of await run('styleDescriptions'))assert.equal(row.actual,row.expected)
    await rich.getByRole('button',{name:'装备说明',exact:true}).hover()
    await tooltip.getByText('残疫',{exact:true}).waitFor()
    assert.equal(await color(tooltip,'stat'),'rgb(255, 215, 0)')
    assert.equal(await color(tooltip,'magicdamage'),'rgb(10, 203, 230)')
    assert.equal(await color(tooltip,'magicresist'),'rgb(79, 223, 255)')
    assert.ok(!(await tooltip.textContent()).includes('<mainText>'))
    await tooltip.screenshot({path:path.join(out,'装备说明_原始标记颜色_模拟.png')})
    await rich.getByRole('button',{name:'装备说明',exact:true}).click()
    await tooltip.waitFor({state:'hidden'})
    await rich.getByRole('button',{name:'符文说明',exact:true}).hover()
    await tooltip.getByText('召唤：艾黎',{exact:true}).waitFor()
    assert.ok((await tooltip.locator('.sona-game-description').textContent()).length>30)
    assert.ok(await tooltip.locator('[data-game-semantic]').count()>0)
    await page.mouse.move(2,2)
    const secondary=rich.locator('.rh-runes-detail-button img').last()
    await secondary.hover()
    await tooltip.getByText('创造性的工具并扭转常规',{exact:true}).waitFor()
    await tooltip.screenshot({path:path.join(out,'副系符文_官方说明_模拟.png')})
    await page.mouse.move(2,2)
    await rich.getByRole('button',{name:'安全检查',exact:true}).focus()
    await tooltip.getByText('输入安全检查',{exact:true}).waitFor()
    assert.match(await tooltip.textContent(),/<b>原文<\/b>/)
    assert.equal(await tooltip.locator('img,script,font').count(),0)
    assert.equal(await page.evaluate(()=>window.qaExecuted),undefined)
    const magic=await tooltip.locator('[data-game-semantic="magicdamage"]').allTextContents()
    assert.equal(magic.join(''),'魔法伤害  魔法伤害')
    await page.keyboard.press('Enter');await tooltip.waitFor({state:'hidden'})
    await run('panel')
    const kit=page.locator('.sobp-official-tooltip')
    await rich.locator('.sobp-last-item .sobp-icon-tooltip-wrap').first().hover()
    await kit.getByText('残疫',{exact:true}).waitFor()
    assert.equal(await color(kit,'stat'),'rgb(255, 215, 0)')
    assert.equal(await color(kit,'abilitypower'),'rgb(120, 108, 255)')
    assert.equal(await color(kit,'magicdamage'),'rgb(10, 203, 230)')
    assert.match(await kit.textContent(),/90法术强度/)
    assert.ok(!(await kit.textContent()).includes('法术强度90'))
    await page.waitForFunction(()=>getComputedStyle(document.querySelector('.sobp-official-tooltip')).opacity==='1')
    await kit.screenshot({path:path.join(out,'配装说明_语义颜色_模拟.png')})
    await rich.locator('.sobp-last-item .sobp-icon-tooltip-wrap').first().click()
    await kit.waitFor({state:'hidden'})
    await rich.locator('.sobp-augment .sobp-icon-tooltip-wrap').first().hover()
    await kit.getByText('泰坦的坚决',{exact:true}).waitFor()
    assert.equal(await color(kit,'armor'),'rgb(240, 186, 87)')
    assert.equal(await color(kit,'magicresist'),'rgb(79, 223, 255)')
    await page.waitForFunction(()=>getComputedStyle(document.querySelector('.sobp-official-tooltip')).opacity==='1')
    await kit.screenshot({path:path.join(out,'海克斯说明_属性颜色_模拟.png')})
    await page.mouse.move(2,2);await kit.waitFor({state:'hidden'})
    await run('skins')
    await rich.getByTestId('skin-0').getByText('模拟皮肤名称',{exact:true}).waitFor()
    assert.equal(await rich.getByTestId('skin-1').textContent(),'模拟皮肤名称')
    assert.equal(await rich.getByTestId('skin-2').textContent(),'')
    assert.equal(await rich.getByTestId('skin-3').textContent(),'已记录的皮肤')
    assert.equal(skinRequests,1,'same champion skin metadata is shared')
    console.log('[verify] native items/runes, all five official style descriptions, ARAMKit item/augment colors, nested semantics, safe text rendering, and click dismissal passed')
  } finally { await run('clear'); await page.unroute('https://data.aramkit.cn/assets/**',assetRoute); await page.unroute('**/lol-game-data/assets/v1/champions/86.json',skinRoute) }
}
