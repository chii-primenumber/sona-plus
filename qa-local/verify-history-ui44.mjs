import assert from 'node:assert/strict'
import path from 'node:path'
import { selectOption } from './select-option.mjs'

export async function verifyHistoryUi44(page,profile,out) {
  const position=profile.getByLabel('筛选位置',{exact:true})
  await position.click()
  assert.equal(await page.getByRole('listbox').getByRole('option').count(),6)
  assert.deepEqual(await page.getByRole('listbox').getByRole('option').evaluateAll((nodes)=>nodes.map((node)=>node.getAttribute('data-value'))),['','TOP','JUNGLE','MIDDLE','BOTTOM','UTILITY'])
  await page.keyboard.press('Escape')
  await profile.getByRole('button',{name:/英雄统计/}).click()
  assert.equal(await profile.getByLabel('英雄统计排序').count(),0)
  const table=profile.locator('.rh-champion-table')
  const rates=async()=>table.locator('tbody tr td:nth-child(3)').allTextContents().then((values)=>values.map((value)=>Number(value.replace('%',''))))
  const winRate=profile.getByRole('button',{name:'胜率排序',exact:true})
  await winRate.click();const desc=await rates();assert.deepEqual(desc,[...desc].sort((a,b)=>b-a))
  assert.equal(await table.locator('th').nth(2).getAttribute('aria-sort'),'descending')
  await winRate.click();const asc=await rates();assert.deepEqual(asc,[...asc].sort((a,b)=>a-b))
  assert.equal(await table.locator('th').nth(2).getAttribute('aria-sort'),'ascending')
  const header=await table.locator('th').first().evaluate((node)=>getComputedStyle(node).backgroundColor)
  assert.equal(header,'rgba(1, 10, 19, 0.38)')
  await profile.screenshot({path:path.join(out,'英雄统计_表头排序与半透明_模拟.png')})
  await profile.getByRole('button',{name:/战绩明细/}).click()
  await profile.locator('.rh-expand').first().click()
  const report=profile.locator('.rh-report').first(), slider=report.getByRole('group',{name:'战报分组',exact:true})
  assert.equal(await slider.locator('.sona-segmented-thumb').count(),1)
  await slider.getByRole('button',{name:'战斗与经济',exact:true}).focus();await page.keyboard.press('ArrowRight')
  assert.equal(await slider.getByRole('button',{name:'治疗、控制与视野',exact:true}).getAttribute('aria-pressed'),'true')
  assert.equal(await report.locator('.rh-report-outcome--win').evaluate((node)=>getComputedStyle(node).color),'rgb(0, 199, 217)')
  assert.equal(await report.locator('.rh-report-outcome--loss').evaluate((node)=>getComputedStyle(node).color),'rgb(255, 70, 85)')
  await report.screenshot({path:path.join(out,'战报_滑块与胜负颜色_模拟.png')})
  await selectOption(page,profile.getByLabel('游戏模式'),'450')
  await profile.locator('.rh-match').first().waitFor();assert.equal(await position.count(),0)
  await selectOption(page,profile.getByLabel('游戏模式'),'2400')
  await profile.locator('.rh-match').first().waitFor();assert.equal(await position.count(),0)
  await selectOption(page,profile.getByLabel('游戏模式'),'420')
  await position.waitFor();assert.equal(await position.getAttribute('data-value'),'')
  await page.keyboard.press('Escape');await profile.waitFor({state:'hidden'})
  await page.getByRole('button',{name:'模拟进游戏',exact:true}).click()
  await page.locator('[data-sona-team-history="game"]').click()
  const team=page.getByTestId('game-history')
  await team.locator('.rh-team-card').nth(9).waitFor()
  assert.ok((await team.locator('.rh-team-portrait img').evaluateAll((nodes)=>nodes.map((node)=>getComputedStyle(node).borderRadius))).every((radius)=>radius==='5px'))
  await team.screenshot({path:path.join(out,'对局详情_圆角方形头像_模拟.png')})
  await page.keyboard.press('Escape');await team.waitFor({state:'hidden'})
  console.log('[verify] column sorting both directions, transparent headers, combat/support slider, outcome colors, six lane choices, non-Rift gating and rounded-square team portraits passed')
}
